#!/usr/bin/env python3
"""gen-ipvec.py - writes tests/ipvec.h: IPv4 TCP and UDP frames with checksums computed here, in
Python, independently of core/mp_ipck.c, for tests/test_ipck.c.  Run: python3 tools/gen-ipvec.py"""
import os, socket, struct

def csum(b):
    if len(b) % 2:
        b += b"\0"
    s = sum(struct.unpack(">%dH" % (len(b) // 2), b))
    while s >> 16:
        s = (s & 0xFFFF) + (s >> 16)
    return (~s) & 0xFFFF

def frame(proto, payload, src="10.0.0.1", dst="10.0.0.2"):
    if proto == 6:
        seg = struct.pack(">HHIIBBHHH", 1234, 17007, 1, 2, 5 << 4, 0x18, 4096, 0, 0) + payload
    else:
        seg = struct.pack(">HHHH", 1234, 17007, 8 + len(payload), 0) + payload
    ip = struct.pack(">BBHHHBBH4s4s", 0x45, 0, 20 + len(seg), 1, 0, 64, proto, 0,
                     socket.inet_aton(src), socket.inet_aton(dst))
    ip = ip[:10] + struct.pack(">H", csum(ip)) + ip[12:]
    ph = socket.inet_aton(src) + socket.inet_aton(dst) + struct.pack(">BBH", 0, proto, len(seg))
    off = 16 if proto == 6 else 6
    seg = seg[:off] + struct.pack(">H", csum(ph + seg)) + seg[off + 2:]
    return bytes.fromhex("00801912345602005e000001") + b"\x08\x00" + ip + seg

def arr(name, b):
    out = ["static const uint8_t %s[%d] = {" % (name, len(b))]
    for i in range(0, len(b), 16):
        out.append("    " + ", ".join("0x%02x" % x for x in b[i:i + 16]) + ",")
    return "\n".join(out + ["};", ""])

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(root, "tests", "ipvec.h"), "w") as f:
    f.write("/* ipvec.h - generated by tools/gen-ipvec.py (checksums computed in Python). */\n")
    f.write(arr("k_tcp", frame(6, bytes((i * 7) & 255 for i in range(1460)))))  # full-size frame
    f.write(arr("k_tcp_small", frame(6, bytes(range(10)))))
    f.write(arr("k_udp_odd", frame(17, bytes(range(33)))))
