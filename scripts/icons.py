#!/usr/bin/env python3
"""icons.py - MoofPort's icon family from pixel text to Rez, plus a preview.

    scripts/icons.py rez                 # writes mac/icons/icons.r (ICN#/ics# per application)
    scripts/icons.py preview out.png     # all icons and masks side by side, 8x

The source is mac/icons/moofport.icn.txt: sections "base 32", "base 16", "badge <app> 32",
"badge <app> 16"; rows of '#' (black), '.' (white, inside the mask), ' ' (outside the mask).
Each application's icon is the base with its badge drawn over the bottom-right corner (badge
' ' cells leave the base alone). The mask is every non-' ' cell. Original artwork for MoofPort.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "mac", "icons", "moofport.icn.txt")
OUT = os.path.join(ROOT, "mac", "icons", "icons.r")
# application -> (resource id base, creator); the badge of the same name
APPS = [("installer", "MoofPortInstall", "MPIN"), ("tune", "MoofTune", "MPTU"),
        ("stat", "MoofStat", "MPST")]


def load():
    """Sections of rows; lines starting with ';' are comments, blank lines are skipped. Rows
    shorter than the section's size are padded with ' ' (editors strip trailing spaces), and
    missing rows at the bottom are empty."""
    secs, cur = {}, None
    for line in open(SRC).read().split("\n"):
        if line.startswith(";") or not line.strip():
            continue
        if line[0].isalpha():
            cur = tuple(line.split())
            secs[cur] = []
            continue
        if cur is None:
            sys.exit("icons.py: rows before the first section")
        secs[cur].append(line)
    for k, rows in secs.items():
        n = int(k[-1])
        if k[0] == "badge":                 # a badge is smaller: pad to its own widest row
            w = max(len(r) for r in rows)
            if len(rows) > n or w > n:
                sys.exit("icons.py: badge %s is larger than %d" % (" ".join(k), n))
            secs[k] = [r.ljust(w) for r in rows]
            continue
        rows = [r.ljust(n) for r in rows] + [" " * n] * (n - len(rows))   # empty rows at the bottom
        if len(rows) != n or any(len(r) != n for r in rows):
            sys.exit("icons.py: section %s must be %dx%d, got %d rows, widths %s"
                     % (" ".join(k), n, n, len(rows), sorted(set(len(r) for r in rows))))
        bad = set("".join(rows)) - set("#. ")
        if bad:
            sys.exit("icons.py: section %s has characters %r" % (" ".join(k), "".join(bad)))
        secs[k] = rows
    return secs


def compose(secs, app, n):
    rows = [list(r) for r in secs[("base", str(n))]]
    badge = secs.get(("badge", app, str(n)))
    if badge:
        h, w = len(badge), len(badge[0])
        for y, r in enumerate(badge):
            for x, c in enumerate(r[:w]):
                if c != " ":
                    rows[n - h + y][n - w + x] = c
    return ["".join(r) for r in rows]


def bits(rows, pred):
    out = bytearray()
    n = len(rows)
    for r in rows:
        v = 0
        for c in r:
            v = (v << 1) | (1 if pred(c) else 0)
        out += v.to_bytes(n // 8, "big")
    return bytes(out)


def hexlines(b, per):
    return "\n".join('    $"%s"' % " ".join(b[i:i + per][j:j + 4].hex().upper()
                                         for j in range(0, len(b[i:i + per]), 4))
                     for i in range(0, len(b), per))


def rez(secs):
    out = ["/* icons.r - generated by scripts/icons.py from mac/icons/moofport.icn.txt; do not edit.",
           " * Per application: ICN# and ics# 128, the owner resource (creator, id 0), FREF 128",
           " * (APPL, local icon 0) and BNDL 128. Include it in the application's .r and give the",
           " * application the same creator (CMakeLists.txt CREATOR). */", ""]
    for app, name, creator in APPS:
        big, small = compose(secs, app, 32), compose(secs, app, 16)
        out.append("#ifdef ICONS_%s" % app.upper())
        out.append("data 'ICN#' (128) {")
        out.append(hexlines(bits(big, lambda c: c == "#"), 16))
        out.append("    /* mask */")
        out.append(hexlines(bits(big, lambda c: c != " "), 16))
        out.append("};")
        out.append("data 'ics#' (128) {")
        out.append(hexlines(bits(small, lambda c: c == "#"), 16))
        out.append("    /* mask */")
        out.append(hexlines(bits(small, lambda c: c != " "), 16))
        out.append("};")
        sig = "%s 1.0" % name
        out.append("data '%s' (0) { $\"%02X\" \"%s\" };" % (creator, len(sig), sig))
        out.append("resource 'FREF' (128) { 'APPL', 0, \"\" };")
        out.append("resource 'BNDL' (128) {\n    '%s', 0,\n    {\n        'ICN#', { 0, 128 };\n"
                   "        'FREF', { 0, 128 }\n    }\n};" % creator)
        out.append("#endif\n")
    open(OUT, "w").write("\n".join(out))
    print("wrote", OUT)


def preview(secs, path):
    from PIL import Image, ImageDraw
    S, G = 8, 24
    cols = len(APPS)
    w = G + cols * (32 * S * 2 + 16 * S + 3 * G)
    h = G * 2 + 32 * S + 40
    img = Image.new("RGB", (w, h), (170, 170, 170))
    d = ImageDraw.Draw(img)
    x0 = G
    for app, name, creator in APPS:
        d.text((x0, 6), "%s ('%s')" % (name, creator), fill=(0, 0, 0))
        big, small = compose(secs, app, 32), compose(secs, app, 16)
        for k, (rows, as_mask) in enumerate([(big, False), (big, True), (small, False)]):
            ox = x0 + [0, 32 * S + G, 64 * S + 2 * G][k]
            for y, r in enumerate(rows):
                for x, c in enumerate(r):
                    if as_mask:
                        col = (0, 0, 0) if c != " " else (255, 255, 255)
                    elif c == " ":
                        continue
                    else:
                        col = (0, 0, 0) if c == "#" else (255, 255, 255)
                    d.rectangle([ox + x * S, G + y * S, ox + x * S + S - 1, G + y * S + S - 1],
                                fill=col)
        # actual size, on white and on the desktop grey
        for k, bg in enumerate([(255, 255, 255), (170, 170, 170)]):
            ox, oy = x0 + 64 * S + 2 * G + k * 40, G + 16 * S + G
            d.rectangle([ox - 2, oy - 2, ox + 33, oy + 33], fill=bg)
            for y, r in enumerate(big):
                for x, c in enumerate(r):
                    if c != " ":
                        img.putpixel((ox + x, oy + y), (0, 0, 0) if c == "#" else (255, 255, 255))
        x0 += 32 * S * 2 + 16 * S + 3 * G
    d.text((G, h - 22), "each app: 32x32 icon, its mask, 16x16 small icon; actual size below the small icon",
           fill=(0, 0, 0))
    img.save(path)
    print("wrote", path)


def main():
    secs = load()
    if len(sys.argv) >= 2 and sys.argv[1] == "rez":
        rez(secs)
    elif len(sys.argv) >= 3 and sys.argv[1] == "preview":
        preview(secs, sys.argv[2])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
